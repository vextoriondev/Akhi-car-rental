/** Build prefilled WhatsApp message URL */
export function buildWhatsAppUrl({
  phone,
  carName,
  yearOrRange,
  category,
  locale = 'en',
}: {
  phone: string
  carName?: string
  yearOrRange?: string | number
  category?: string
  locale?: Locale
}) {
  const cleanPhone = phone.replace(/\D/g, '')
  let msg = ''
  if (carName) {
    if (locale === 'bn') {
      msg = `আসসালামু আলাইকুম, আমি আখি কার রেন্টাল থেকে "${carName}"${yearOrRange ? ` (${yearOrRange})` : ''}${category ? ` [${category}]` : ''} ভাড়া নেওয়ার ব্যাপারে তথ্য ও বুকিং জানতে চাচ্ছি।`
    } else {
      msg = `Hello Akhi Car Rental! I would like to inquire about renting the "${carName}"${yearOrRange ? ` (${yearOrRange})` : ''}${category ? ` [${category}]` : ''}. Please share availability and current rates.`
    }
  } else {
    msg =
      locale === 'bn'
        ? 'আসসালামু আলাইকুম, আমি গাড়ি ভাড়া নেওয়ার বিষয়ে আলোচনা করতে চাই।'
        : 'Hello Akhi Car Rental! I would like to inquire about renting a vehicle.'
  }
  return `https://wa.me/${cleanPhone}?text=${encodeURIComponent(msg)}`
}
